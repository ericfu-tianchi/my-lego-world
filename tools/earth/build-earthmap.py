# Bake the globe's colour map from real satellite imagery (2026-10-02; Eric: the hand-drawn rectangles of desert looked nothing like Earth).
# Sources (public domain, NASA Earth Observatory, Blue Marble Next Generation, R. Stöckli et al.), vendored in vendor/earth/:
#   world.200407.3x5400x2700.jpg            — July surface reflectance (land colour, ice)
#   world.topo.bathy.200406.3x5400x2700.jpg — June with bathymetry shading (shelf seas vs deep ocean)
# Output: src/scenes/earthmap.ts — a 720 × 360 grid (0.5°) of LEGO colour classes, row 0 at 89.75°N, column 0 at 179.75°W, 4 bits per cell.
#   python3 tools/earth/build-earthmap.py
import base64, colorsys, os
from PIL import Image, ImageFilter
ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
W, H = 720, 360
CLASSES = ['DarkBlue', 'DarkAzure', 'MediumAzure', 'White', 'Tan', 'DarkTan', 'MediumNougat', 'OliveGreen', 'BrightGreen', 'Green', 'DarkGreen', 'LightBluishGray']
land = Image.open(os.path.join(ROOT, 'vendor/earth/world.200407.3x5400x2700.jpg')).convert('RGB').filter(ImageFilter.BoxBlur(3)).resize((W, H), Image.BOX)
bath = Image.open(os.path.join(ROOT, 'vendor/earth/world.topo.bathy.200406.3x5400x2700.jpg')).convert('RGB').filter(ImageFilter.BoxBlur(3)).resize((W, H), Image.BOX)

def classify(lp, bp):
  # thresholds read off sampled places (Sahara v .78 g .02, Gobi/Tibet v .5, Australia r/g 1.7, Sahel/US plains g .05, Europe/China v .28,
  # Amazon/Siberia v .15; Bahamas and Sunda shelf bathy luminance ~.21, open Pacific ~.05)
  r, g, b = [c / 255 for c in lp]; h, s, v = colorsys.rgb_to_hsv(r, g, b)
  br, bg, bb = [c / 255 for c in bp]; lum = 0.3 * br + 0.59 * bg + 0.11 * bb
  if v > 0.72 and s < 0.2: return 'White'                                         # ice, snow, sea ice
  if v < 0.13 and b >= r or (bb > br * 1.6 and bb > bg * 1.15 and v < 0.2):       # ocean (near-black navy in the July image)
    return 'MediumAzure' if lum > 0.32 else 'DarkAzure' if lum > 0.16 else 'DarkBlue'
  gr = g - (r + b) / 2
  if r > g * 1.4: return 'MediumNougat'                                            # red deserts: central Australia, Namib
  if gr < 0.035: return 'Tan' if v > 0.62 else 'DarkTan'                           # sand seas; stony plateaus (Gobi, Tibet, Iran)
  if gr < 0.06: return 'OliveGreen'                                                # steppe and savanna (Sahel, Great Plains, Deccan)
  if v < 0.2: return 'DarkGreen'                                                   # rainforest, taiga
  return 'Green' if v < 0.31 else 'BrightGreen'                                    # temperate farmland and forest
grid = []
for y in range(H):
  for x in range(W):
    grid.append(CLASSES.index(classify(land.getpixel((x, y)), bath.getpixel((x, y)))))
# a 3×3 majority filter on land classes only, so colours form regions (the satellite has texture a stud cannot carry)
def at(x, y): return grid[min(H - 1, max(0, y)) * W + (x % W)]
out = grid[:]
for y in range(H):
  for x in range(W):
    c = at(x, y)
    if c <= 2: continue
    votes = {}
    for dy in (-1, 0, 1):
      for dx in (-1, 0, 1):
        k = at(x + dx, y + dy)
        if k > 2: votes[k] = votes.get(k, 0) + 1
    out[y * W + x] = max(votes.items(), key=lambda kv: (kv[1], kv[0] == c))[0]
packed = bytearray((W * H + 1) // 2)
for i, c in enumerate(out): packed[i >> 1] |= c << (4 * (i & 1))
b64 = base64.b64encode(bytes(packed)).decode()
src = f"""// Generated by tools/earth/build-earthmap.py from NASA Blue Marble Next Generation (public domain). Do not edit.
// {W} × {H} cells of 0.5°, row 0 at 89.75°N, column 0 at 179.75°W; 4-bit LEGO colour classes.
export const EARTH_CLASSES = {CLASSES!r};
const B64 = '{b64}';
const NodeBuffer = (globalThis as unknown as {{ Buffer?: {{ from(s: string, enc: string): Uint8Array }} }}).Buffer;
const BYTES = NodeBuffer ? new Uint8Array(NodeBuffer.from(B64, 'base64')) : Uint8Array.from(atob(B64), (c) => c.charCodeAt(0));
/** the LEGO colour of the earth at (lat, lon), from satellite imagery */
export function earthColor(lat: number, lon: number): string {{
  let x = Math.floor((lon + 180) * 2); x = ((x % {W}) + {W}) % {W}; const y = Math.min({H - 1}, Math.max(0, Math.floor((90 - lat) * 2))); const i = y * {W} + x;
  return EARTH_CLASSES[(BYTES[i >> 1] >> (4 * (i & 1))) & 15];
}}
"""
open(os.path.join(ROOT, 'src/scenes/earthmap.ts'), 'w').write(src.replace("['", "['").replace("'DarkBlue'", "'DarkBlue'"))
from collections import Counter
print('cells', W * H, Counter(CLASSES[c] for c in out).most_common())
# a preview, one pixel per cell, for checking against the source
pal = {'DarkBlue': (10, 52, 99), 'DarkAzure': (7, 139, 201), 'MediumAzure': (54, 174, 191), 'White': (244, 244, 244), 'Tan': (228, 205, 158), 'DarkTan': (149, 138, 115), 'MediumNougat': (170, 125, 85), 'OliveGreen': (155, 154, 90), 'BrightGreen': (75, 159, 74), 'Green': (35, 120, 65), 'DarkGreen': (24, 70, 50), 'LightBluishGray': (160, 165, 169)}
pv = Image.new('RGB', (W, H)); pv.putdata([pal[CLASSES[c]] for c in out]); pv.save(os.path.join(ROOT, 'vendor/earth/earthmap-preview.png'))
